    const box = await book.boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 55, box.y + box.height / 2 + 20, {steps:5}); await page.mouse.up();
    assert.equal(new URL(page.url()).pathname.endsWith('index.html'), true, 'dragging a book must not navigate');
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.waitForFunction(() => document.body.dataset.motion === 'reduced');
    assert.equal(await page.evaluate(() => window.gsap.isTweening('.studio-book')), false);
