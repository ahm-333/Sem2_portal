// Copy existing question text and answer identities into one lazy bank without executing teaching-page UI.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {parse}=require('espree');
function extractArrays(html,names){
  const found=[];
  for(const match of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)){
    if(/\bsrc\s*=|application\/json|module/.test(match[1]))continue;
    const source=match[2];
    const tree=parse(source,{ecmaVersion:2022,range:true});
    function visit(node){
      if(!node||typeof node!=='object')return;
      if(node.type==='VariableDeclarator'&&names.includes(node.id?.name)&&node.init?.type==='ArrayExpression'){
        found.push(...vm.runInNewContext(source.slice(...node.init.range),{}, {timeout:1000}));
        return;
      }
      for(const value of Object.values(node))if(Array.isArray(value))value.forEach(visit);else if(value&&typeof value==='object')visit(value);
    }
    visit(tree);
  }
  return found;
}
function buildQuestionBank(root){
  const bank={};
  const add=(courseId,questions,sourceUrl,lectureId,lectureLabel)=>{
    bank[courseId]||=[];
    for(const q of questions){
      const options=q.options.map(option=>typeof option==='string'?option:option.text);
      const correct=typeof q.correctOptionId==='string'?q.options.findIndex(option=>option.id===q.correctOptionId):q.correct;
      const question=q.question||q.prompt||q.q;
      const explanation=q.explanation||q.feedback?.[q.correctOptionId];
      if(!question||!explanation||!Number.isInteger(correct)||correct<0||correct>=options.length)throw new Error('Invalid reviewed question '+sourceUrl+':'+q.id);
      bank[courseId].push({id:sourceUrl+':'+q.id,lectureId:String(lectureId),lectureLabel,topic:q.topic||q.objective||q.partLabel||q.blockTitle||lectureLabel,question,options,correct,explanation,sourceUrl});
    }
  };
  for(const [courseId,file,lectureId,label]of [
    ['data-structure','study/ds/lecture-1.html','1','المحاضرة 1: Arrays & Templates'],
    ['data-structure','study/ds/lecture-3.html','3','المحاضرة 3: Recursion'],
    ['computer-architecture','study/arch/chapter-7.html','5','المحاضرة 5: Input / Output & DMA'],
    ['database-systems','study/db/chapter-1.html','2','المحاضرة 2: Databases and Database Users'],
    ['database-systems','study/db/chapter-2.html','3','المحاضرة 3: Database Concepts & Architecture']
  ])add(courseId,extractArrays(fs.readFileSync(path.join(root,file),'utf8'),['quizQuestions','mcqQuestions']),file,lectureId,label);
  const scope={window:{}};vm.createContext(scope);
  vm.runInContext(fs.readFileSync(path.join(root,'js/lecture-explanations-data.js'),'utf8'),scope);
  for(const [courseId,lectures]of Object.entries(scope.window.LECTURE_EXPLANATIONS))for(const [id,lesson]of Object.entries(lectures)){
    add(courseId,lesson.fullQuiz||[],'subject.html?id='+courseId+'&lecture='+id,id,'المحاضرة '+id);
  }
  const catalog=require(path.join(root,'education-preview/os/course-catalog.js'));
  for(const unit of catalog.units){
    const context={window:{}};vm.runInNewContext(fs.readFileSync(path.join(root,'education-preview/os',unit.file),'utf8'),context);
    add('operating-system',context.window.OSPilotLesson.questions,'education-preview/os/index.html?unit='+unit.id,String(unit.chapter),'الفصل '+unit.chapter);
  }
  const power={window:{}};vm.runInNewContext(fs.readFileSync(path.join(root,'js/course-power-data.js'),'utf8'),power);
  for(const courseId of ['computer-graphics','report-writing'])for(const q of power.window.COURSE_POWER_DATA[courseId].midtermQuestions){
    add(courseId,[q],'subject.html?id='+courseId,q.lectureId,q.lectureLabel);
  }
  fs.writeFileSync(path.join(root,'js/course-question-bank.js'),'// Generated by npm run build from existing question data; scientific content is unchanged.\nwindow.COURSE_QUESTION_BANK = '+JSON.stringify(bank)+';\n');
  console.log('Source question bank: '+Object.entries(bank).map(([id,qs])=>id+'='+qs.length).join(', '));
  return bank;
}
if(require.main===module)buildQuestionBank(path.resolve(__dirname,'..'));
module.exports={buildQuestionBank,extractArrays};
