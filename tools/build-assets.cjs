const fs = require('node:fs');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const vm = require('node:vm');
const {studyVersion} = require('./study-version.cjs');
const {extractStudyCatalog} = require('./content-catalog.cjs');
const root = path.resolve(__dirname,'..');
const result = spawnSync(process.execPath,[require.resolve('tailwindcss/lib/cli.js'),'-c','tailwind.config.cjs','-i','css/tailwind-input.css','-o','css/tailwind.css','--minify'],{cwd:root,stdio:'inherit'});
if (result.status !== 0) process.exit(result.status || 1);
fs.copyFileSync(path.join(path.dirname(require.resolve('tailwindcss/package.json')),'LICENSE'),path.join(root,'css/TAILWIND-LICENSE'));
const vendor = path.join(root,'js/vendor');
fs.mkdirSync(vendor,{recursive:true});
const lucide = path.dirname(require.resolve('lucide/package.json'));
fs.copyFileSync(path.join(lucide,'dist/umd/lucide.min.js'),path.join(vendor,'lucide.min.js'));
fs.copyFileSync(path.join(lucide,'LICENSE'),path.join(vendor,'LUCIDE-LICENSE'));
// The opening scene is lazy-loaded and has no CDN dependency at runtime.
const threeRoot = path.resolve(path.dirname(require.resolve('three')), '..');
const threeVendor = path.join(vendor,'three');
fs.mkdirSync(threeVendor,{recursive:true});
for (const file of ['three.module.js','three.core.js']) fs.copyFileSync(path.join(threeRoot,'build',file),path.join(threeVendor,file));
fs.copyFileSync(path.join(threeRoot,'LICENSE'),path.join(threeVendor,'LICENSE'));
const studySource = fs.readFileSync(path.join(root,'js/lecture-explanations-data.js'),'utf8');
const scope = {window:{}};
vm.createContext(scope);
vm.runInContext(studySource,scope);
const catalog = extractStudyCatalog(scope.window.LECTURE_EXPLANATIONS);
const version = studyVersion(studySource);
fs.writeFileSync(path.join(root,'js/study-catalog.js'),'// Generated by npm run build; the full study data is loaded on demand.\nwindow.STUDY_CATALOG = '+JSON.stringify(catalog)+';\nwindow.STUDY_DATA_VERSION = '+JSON.stringify(version)+';\n');
